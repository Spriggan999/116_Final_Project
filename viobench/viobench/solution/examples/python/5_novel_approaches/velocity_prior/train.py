"""Train the IMU-history velocity prior and export it as a C++ header.

Data: collector recordings (scenes 20-59), split by scene: training < --val-from,
validation >= --val-from. Never uses public (1) or held-out (192-199) scenes.
The exported sigma per body axis is the validation RMSE, so the filter receives an
honest uncertainty. Inference runs in C++ (estimator/solution.cpp, VEL_PRIOR=1).
"""
import argparse
import json
from pathlib import Path
import re
import numpy as np
import torch
from dataset import load, recordings, BIN, HISTORY

HERE = Path(__file__).resolve().parent


def array(name, values):
    flat = ', '.join(f'{v:.8g}f' for v in np.asarray(values, dtype=np.float64).ravel())
    return f'static const float {name}[{np.asarray(values).size}] = {{{flat}}};\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', default='/var/tmp/novel-approaches-94445')
    parser.add_argument('--val-from', type=int, default=50)
    parser.add_argument('--hidden', type=int, nargs=2, default=[64, 32])
    parser.add_argument('--epochs', type=int, default=3000)
    parser.add_argument('--out', type=Path, default=HERE.parent/'estimator'/'velocity_prior_weights.h')
    args = parser.parse_args()
    paths = recordings(args.root)
    scene = lambda p: int(re.search(r'_s(\d+)_', p).group(1))
    held = set(range(1, 18)) | set(range(192, 200))
    if any(scene(p) in held for p in paths):
        raise ValueError('public/held-out scene among the training recordings')
    tr = [p for p in paths if scene(p) < args.val_from]
    va = [p for p in paths if scene(p) >= args.val_from]
    Xtr, Ytr = map(np.concatenate, load(tr))
    Xva, Yva = map(np.concatenate, load(va))
    mu, sd = Xtr.mean(0), Xtr.std(0)+1e-6
    dev = 'cuda' if torch.cuda.is_available() else 'cpu'
    T = lambda a: torch.tensor(a, dtype=torch.float32, device=dev)
    A, B, Yt, Yv = T((Xtr-mu)/sd), T((Xva-mu)/sd), T(Ytr), T(Yva)
    torch.manual_seed(0)
    h1, h2 = args.hidden
    net = torch.nn.Sequential(torch.nn.Linear(A.shape[1], h1), torch.nn.Tanh(), torch.nn.Linear(h1, h2),
                              torch.nn.Tanh(), torch.nn.Linear(h2, 3)).to(dev)
    opt = torch.optim.AdamW(net.parameters(), 3e-3, weight_decay=1e-2)
    best, best_state = float('inf'), None
    for epoch in range(args.epochs):
        loss = ((net(A)-Yt)**2).sum(1).mean()
        opt.zero_grad(); loss.backward(); opt.step()
        if epoch % 25 == 0:
            with torch.no_grad():
                val = float(((net(B)-Yv)**2).sum(1).mean().sqrt())
            if val < best:
                best, best_state = val, {k: v.detach().clone() for k, v in net.state_dict().items()}
    net.load_state_dict(best_state)
    with torch.no_grad():
        err = (net(B)-Yv).cpu().numpy()
    sigma = np.sqrt((err**2).mean(0))
    zero = float(np.sqrt((Yva**2).sum(1).mean()))
    report = dict(train_flights=len(tr), val_flights=len(va), val_rmse=best, val_rmse_per_axis=sigma.tolist(),
                  zero_prior_rmse=zero, hidden=args.hidden, history_s=HISTORY*BIN*0.005)
    print(json.dumps(report, indent=2))
    W = {k: v.cpu().numpy() for k, v in net.state_dict().items()}
    text = ('// Generated by velocity_prior/train.py. ' + json.dumps(report) + '\n#pragma once\n'
            f'#define VP_BIN {BIN}\n#define VP_HIST {HISTORY}\n#define VP_IN {A.shape[1]}\n#define VP_H1 {h1}\n#define VP_H2 {h2}\n'
            + array('vp_mean', mu) + array('vp_inv_std', 1/sd)
            + array('vp_w1', W['0.weight']) + array('vp_b1', W['0.bias'])
            + array('vp_w2', W['2.weight']) + array('vp_b2', W['2.bias'])
            + array('vp_w3', W['4.weight']) + array('vp_b3', W['4.bias']) + array('vp_sigma', sigma))
    args.out.write_text(text)
    (args.out.with_suffix('.json')).write_text(json.dumps(report, indent=2))
    print('wrote', args.out)


if __name__ == '__main__':
    main()
